import assert from 'node:assert/strict';
import {sortCatalog,catalogPage,pickUnsolved,readBookmarks,recentAttempts} from '../dist/library-discovery.js';
import {readFileSync} from 'node:fs';
const rows=[{id:'a1',title:'Zebra',difficulty:'Hard'},{id:'b2',title:'Alpha',difficulty:'Easy'},{id:'c3',title:'Beta',difficulty:'Medium'}],numbers=new Map(rows.map((p,i)=>[p.id,i+1]));
assert.deepEqual(sortCatalog(rows,'title',numbers).map(p=>p.id),['b2','c3','a1']);
assert.deepEqual(sortCatalog(rows,'difficulty',numbers).map(p=>p.id),['b2','c3','a1']);
assert.deepEqual(sortCatalog(rows,'number-desc',numbers).map(p=>p.id),['c3','b2','a1']);
assert.deepEqual(sortCatalog(rows,'recent',numbers,['c3']).map(p=>p.id),['c3','a1','b2']);
assert.equal(catalogPage(rows,99,2).page,2);
assert.deepEqual(catalogPage(rows,2,2).rows,[rows[2]]);
assert.equal(catalogPage([],1).start,0);
assert.equal(pickUnsolved(rows,{a1:true},false),null);
assert.equal(pickUnsolved(rows,{a1:true},true,()=>0).id,'b2');
assert.equal(pickUnsolved(rows,{a1:true,b2:true,c3:true},true),null);
assert.deepEqual([...readBookmarks({getItem:()=>JSON.stringify(['a1','a1','__proto__',null])},'key')],['a1']);
assert.equal(readBookmarks({getItem(){throw Error('blocked')}},'key').size,0);
assert.deepEqual(recentAttempts([{id:'a1'},{id:'b2'},{id:'a1'}]),['a1','b2']);
const html=readFileSync('dist/index.html','utf8'),app=readFileSync('dist/app.js','utf8');
for(const id of ['libraryPick','librarySort','libraryCompany','libraryProgressBar','libraryPager','libraryContinue'])assert.ok(html.includes('id="'+id+'"'),id);
assert.ok(app.includes('prosolver.bookmarks.v1:"+storageKey'));
assert.ok(html.includes('library-discovery.css?v=1&amp;compact-header=1'));
assert.ok(html.includes('<span id="catalogCount" hidden></span>'),'Keep the count available to updateStats without a visible badge');
assert.ok(html.includes('<h2 class="sr-only">Problems</h2>'));
assert.ok(readFileSync('dist/library-discovery.css','utf8').includes('#mapView .library-heading h2.sr-only'));
assert.ok(readFileSync('dist/library-discovery.css','utf8').includes('#mapView #catalogCount[hidden]{display:none!important}'));
assert.ok(app.includes('"ArrowDown","ArrowUp"'));
assert.ok(app.includes('accountHistoryStatus==="ready"'));
assert.ok(html.indexOf('id="libraryProgressBar"')<html.indexOf('id="libraryContinue"'));
assert.ok(html.indexOf('id="libraryPick"')<html.indexOf('id="searchInput"'));
assert.ok(html.includes('aria-label="Continue last problem"'));
assert.ok(app.indexOf('class="library-status-col"')<app.indexOf('class="library-title-col"'));
assert.ok(!app.includes('<small class="problem-points">'),'Scoring stays out of the compact table');
console.log('PASS: ProSolver catalog discovery, pagination, owner-local bookmarks and safe random selection.');
