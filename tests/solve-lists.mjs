import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {problemSkills,buildSolveLists} from '../dist/solve-lists-model.js';
import {selectedSolveList} from '../dist/solve-lists.js';
const problem=(id,topic,difficulty='Easy',extra={})=>({id,title:id,topic,difficulty,...extra});
const two=problem('two-sum','Hash maps','Easy',{params:[{type:'int[]'}],techniques:['Hashing','hash maps']});
const dp=problem('stairs','DP','Medium',{skills:['Math','Dynamic Programming']});
const ll=problem('cycle','linked list','Medium',{params:[{type:'ListNode'}],techniques:['Two pointers']});
const hard=problem('hard','Array','Hard');
const easy=problem('easy','arrays');
const newTopic=problem('new','Segment Tree');
assert.deepEqual(new Set(problemSkills(two)),new Set(['Hashing','Arrays']));
assert.deepEqual(new Set(problemSkills(dp)),new Set(['Dynamic Programming','Mathematics']));
assert.deepEqual(new Set(problemSkills(ll)),new Set(['Linked Lists','Two Pointers']));
const catalog=[hard,dp,two,ll,easy,newTopic,two];
const lists=buildSolveLists(catalog,{'two-sum':123,stairs:456});
const get=name=>lists.find(l=>l.name===name);
assert.deepEqual(get('Arrays').problems.map(p=>p.id),['two-sum','easy','hard']);
assert.equal(get('Arrays').total,3);
assert.equal(get('Arrays').solved,1);
assert.equal(get('Hashing').total,1);
assert.equal(get('Hashing').solved,1);
assert.equal(get('Mathematics').solved,1);
assert.equal(get('Dynamic Programming').solved,1);
assert.equal(get('Segment Tree').total,1);
assert.equal(buildSolveLists(catalog,{}).find(l=>l.name==='Arrays').solved,0);
assert.equal(buildSolveLists([...catalog,problem('another','Array')]).find(l=>l.name==='Arrays').total,4);
assert.deepEqual(buildSolveLists([]),[]);
assert.deepEqual(problemSkills(problem('missing','')),['Uncategorized']);
assert.deepEqual(new Set(problemSkills(problem('matrix','Matrices','Easy',{params:[{type:'int[][]'}]}))),new Set(['Matrices','Arrays']));
assert.equal(selectedSolveList('#solve-lists/Dynamic%20Programming'),'Dynamic Programming');
assert.equal(selectedSolveList('#solve-lists'),'');
assert.equal(selectedSolveList('#solve-lists/%ZZ'),'');
const html=readFileSync('dist/index.html','utf8'),app=readFileSync('dist/app.js','utf8');
assert.ok(html.includes('id="solve-listsView"'));
assert.ok(html.includes('id="questGrid"'),'Existing library remains');
assert.ok(app.includes('state.solved,accountHistoryStatus,changeProblem'));
for(const page of ['index','community','leaderboard','studio'])assert.ok(readFileSync('dist/'+page+'.html','utf8').includes('./index.html#solve-lists'));
console.log('PASS: automatic Solve Lists, normalized topics, unique membership, shared progress and guarded legacy routing');
