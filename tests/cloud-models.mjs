import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {problems} from "../dist/problems.js";
import {validateProblem} from "../dist/catalog.js";
import {blankProgress,validateProgress,mergeProgress} from "../dist/progress.js";
import {validPublicConfig} from "../dist/cloud.js";
for(const p of problems)assert.equal(validateProblem(p).id,p.id);
assert.throws(()=>validateProblem({...problems[0],method:"return"}));
assert.throws(()=>validateProblem({...problems[0],params:[{name:"x",type:"int"},{name:"x",type:"int"}]}));
assert.throws(()=>validateProblem({...problems[0],tests:[{args:["bad",9],expected:[0,1]}]}));
assert.throws(()=>validateProblem({...problems[0],id:"__proto__"}));
const a=blankProgress(),b=blankProgress();
a.drafts["two-sum"]="local newer code";a.modified["two-sum"]={drafts:200,notes:0,confidence:0};
b.drafts["two-sum"]="remote older code";b.notes["two-sum"]="remote note";b.modified["two-sum"]={drafts:100,notes:300,confidence:0};
a.solved["two-sum"]=100;b.solved["two-sum"]=200;
a.reviews["two-sum"]={anchor:100,step:1};b.reviews["two-sum"]={anchor:200,step:2};
a.days=["2026-11-12"];b.days=["2026-11-12","2026-11-13"];
a.activity=[{id:"two-sum",type:"solved",at:100,passed:5,total:5}];b.activity=[...a.activity,{id:"two-sum",type:"review",at:200,passed:5,total:5}];
const merged=mergeProgress(a,b);
assert.equal(merged.drafts["two-sum"],"local newer code");
assert.equal(merged.notes["two-sum"],"remote note");
assert.equal(merged.solved["two-sum"],100);
assert.deepEqual(merged.reviews["two-sum"],{anchor:100,step:2});
assert.equal(merged.days.length,2);assert.equal(merged.activity.length,2);
assert.deepEqual(mergeProgress(merged,b),merged,"Repeated sync must be idempotent.");
const future=blankProgress();future.drafts["future-problem"]="keep this";assert.equal(validateProgress(future).drafts["future-problem"],"keep this","Catalog growth must preserve valid future progress.");
assert.throws(()=>validateProgress({version:99}));
assert.equal(validPublicConfig({url:"https://example.supabase.co",publishableKey:"sb_publishable_test-key"}),true);
assert.equal(validPublicConfig({url:"https://example.supabase.co",publishableKey:"sb_secret_private"}),false);
assert.equal(validPublicConfig({url:"https://example.supabase.co",publishableKey:"service_role_jwt"}),false);
assert.equal(validPublicConfig({url:"http://example.supabase.co",publishableKey:"sb_publishable_test"}),false);
const index=readFileSync("dist/index.html","utf8");
for(const id of ["accountBtn","accountDialog","googleSignInBtn","studioView","problemForm","studioFields","pTitle","pFrames","syncBadge"])assert.ok(index.includes('id="'+id+'"'),id+" is missing");
assert.ok(!readFileSync("dist/config.js","utf8").includes("sb_secret_"),"Never ship a secret key.");
console.log("PASS: catalog validation, Java contract checks, progress merge conflicts, backup compatibility, idempotent sync, public-key guard, and account/studio UI.");
